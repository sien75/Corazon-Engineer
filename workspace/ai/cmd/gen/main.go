// Command gen generates corazon-internal tool definitions into workspace/ai
// from the repo-root contract files (single source of truth):
//   - contracts/static-{query,query-detail,search,mutation}.yaml + log-*.yaml → internal/tools/tools_gen.go
//
// Run via `go generate ./...` from workspace/ai.
// Note: the system prompt is NOT generated here — it is a static copy kept at
// workspace/ai/internal/ai/system-prompt.md (see system_prompt.go).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

var toolContracts = []string{
	"static-query",
	"static-query-detail",
	"static-search",
	"static-mutation",
	"log-query",
	"log-query-detail",
	"log-search",
	"log-mutation",
}

func main() {
	root := flag.String("root", "", "repo root (default: module dir + ../..)")
	flag.Parse()
	r := *root
	if r == "" {
		wd, err := os.Getwd()
		if err != nil {
			fatal(err)
		}
		r = filepath.Join(wd, "../..")
	}
	moduleDir, err := filepath.Abs(".")
	if err != nil {
		fatal(err)
	}
	genTools(r, moduleDir)
	fmt.Println("gen: ok")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

// ---------- tools ----------

type tool struct {
	Name        string                 `json:"name"`
	Description string                 `json:"description"`
	Parameters  map[string]interface{} `json:"parameters"`
}

func genTools(repoRoot, moduleDir string) {
	dir := filepath.Join(repoRoot, "contracts")
	var out []tool
	for _, id := range toolContracts {
		doc, err := readYAML(filepath.Join(dir, id+".yaml"))
		if err != nil {
			fatal(err)
		}
		request, _ := doc["request"].(map[string]interface{})
		body, _ := request["body"].(map[string]interface{})
		t := tool{
			Name:        strings.ReplaceAll(id, "-", "_"),
			Description: str(doc, "description"),
			Parameters:  bodySchema(body),
		}
		out = append(out, t)
	}
	blob, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		fatal(err)
	}
	content := "// Code generated by cmd/gen; DO NOT EDIT.\n\npackage tools\n\nvar builtinToolsRaw = `" + string(blob) + "`\n"
	writeFile(filepath.Join(moduleDir, "internal", "tools", "tools_gen.go"), content)
}

// ---------- helpers ----------

func readYAML(path string) (map[string]interface{}, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc map[string]interface{}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return doc, nil
}

func writeFile(path, content string) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fatal(err)
	}
}

func str(m map[string]interface{}, k string) string {
	if v, ok := m[k].(string); ok {
		return v
	}
	return ""
}

// bodySchema converts a contract request.body map into a JSON Schema object.
func bodySchema(body map[string]interface{}) map[string]interface{} {
	props := map[string]interface{}{}
	var required []interface{}
	for k, v := range body {
		opt := strings.HasSuffix(k, "?")
		name := strings.TrimSuffix(k, "?")
		props[name] = valueSchema(v)
		if !opt {
			required = append(required, name)
		}
	}
	s := map[string]interface{}{"type": "object", "properties": props}
	if len(required) > 0 {
		s["required"] = required
	}
	return s
}

func valueSchema(v interface{}) map[string]interface{} {
	switch t := v.(type) {
	case string:
		return typeSchema(t)
	case map[string]interface{}:
		return bodySchema(t)
	case []interface{}:
		if len(t) == 1 {
			return map[string]interface{}{"type": "array", "items": valueSchema(t[0])}
		}
		return map[string]interface{}{"type": "array"}
	default:
		return map[string]interface{}{"type": "string"}
	}
}

func typeSchema(s string) map[string]interface{} {
	s = strings.TrimSpace(s)
	if i := strings.Index(s, "|"); i >= 0 {
		return typeSchema(strings.TrimSpace(s[:i]))
	}
	switch s {
	case "string":
		return map[string]interface{}{"type": "string"}
	case "number":
		return map[string]interface{}{"type": "number"}
	case "boolean":
		return map[string]interface{}{"type": "boolean"}
	case "object":
		return map[string]interface{}{"type": "object"}
	}
	if strings.HasPrefix(s, "[") && strings.HasSuffix(s, "]") {
		return map[string]interface{}{"type": "array", "items": typeSchema(strings.TrimSpace(s[1 : len(s)-1]))}
	}
	return map[string]interface{}{"type": "string"}
}
